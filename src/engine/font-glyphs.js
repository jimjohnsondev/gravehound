/**
 * The game's pixel font, written out as pictures you can read and edit.
 *
 * Each glyph is 8 rows tall. A '#' is a lit pixel and a '.' is empty. All rows
 * of one glyph must be the same length, and that length is the glyph's width,
 * so narrow letters like 'i' take up less room than wide ones like 'M'.
 *
 * Where things sit in the 8 rows:
 *   rows 0-5  capitals, digits, and tall lowercase like 'b', 'd', 'h'
 *   rows 2-5  the body of small lowercase letters like 'a', 'e', 'o'
 *   rows 6-7  descenders: the tails of 'g', 'j', 'p', 'q', 'y'
 *
 * To add a character, add an entry here. text.js checks the shapes when the
 * game starts and complains if a glyph has the wrong number of rows.
 */

